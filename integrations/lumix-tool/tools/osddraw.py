"""Draw text into the S5 OSD plane over the service USB (RAM only).

Pixel format verified: 1024 px wide, stride 4096, bytes [A, B, G, R].
A 5x7 bitmap font is scaled up; each written pixel is two 0x9C halfword writes.
"""
import argparse
import sys

sys.path.insert(0, "tools")
import s5svc as S

STRIDE = 4096
WIDTH = 1024

FONT = {
    "H": [0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
    "E": [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F],
    "L": [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F],
    "O": [0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
    "W": [0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A],
    "R": [0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11],
    "D": [0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E],
    " ": [0, 0, 0, 0, 0, 0, 0],
    "!": [0x04, 0x04, 0x04, 0x04, 0x04, 0x00, 0x04],
    "0": [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
    "1": [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E],
    "2": [0x0E, 0x11, 0x01, 0x06, 0x08, 0x10, 0x1F],
    "3": [0x1F, 0x02, 0x04, 0x06, 0x01, 0x11, 0x0E],
    "4": [0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02],
    "5": [0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E],
    "6": [0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E],
    "7": [0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
    "8": [0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E],
    "9": [0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C],
    "V": [0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04],
    "M": [0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11],
    "-": [0, 0, 0, 0x1F, 0, 0, 0],
    "X": [0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11],
    "A": [0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
    "S": [0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E],
}


def draw(svc, base, text, x0, y0, scale, color):
    a, b, g, r = color
    lo = (a | (b << 8)) & 0xFFFF
    hi = (g | (r << 8)) & 0xFFFF
    n = 0
    for ci, ch in enumerate(text):
        glyph = FONT.get(ch.upper(), FONT[" "])
        for gy in range(7):
            for gx in range(5):
                if not (glyph[gy] >> (4 - gx)) & 1:
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        px = x0 + (ci * 6 + gx) * scale + sx
                        py = y0 + gy * scale + sy
                        addr = base + py * STRIDE + px * 4
                        svc.exchange_write(S.build_0x9c(addr, lo))
                        svc.exchange_write(S.build_0x9c(addr + 2, hi))
                        n += 2
    return n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("text")
    ap.add_argument("--base", type=lambda s: int(s, 0), default=0x8DC00000)
    ap.add_argument("--x", type=int, default=120)
    ap.add_argument("--y", type=int, default=120)
    ap.add_argument("--scale", type=int, default=4)
    ap.add_argument("--rgba", default="FF,00,FF,FF")
    ap.add_argument("--delay", type=float, default=0.002)
    a = ap.parse_args()
    color = tuple(int(v, 16) for v in a.rgba.split(","))
    svc = S.Service(settle=a.delay)
    try:
        n = draw(svc, a.base, a.text, a.x, a.y, a.scale, color)
        print("wrote %d halfwords for %r" % (n, a.text))
    finally:
        svc.close()


if __name__ == "__main__":
    main()
