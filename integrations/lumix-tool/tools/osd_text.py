WHITE = (0xFF, 0xFF, 0xFF, 0xFF)   # A,B,G,R


def draw_text(svc, text, x0, y0, scale=4, color=WHITE, base=0x8DC00000):
    a, b, g, r = color
    lo = a | (b << 8)
    hi = g | (r << 8)
    n = 0
    cx = x0
    for ch in text:
        glyph = FONT.get(ch.upper(), FONT[' '])
        for gy in range(7):
            row = glyph[gy]
            for gx in range(5):
                if row[gx] != '1':
                    continue
                for sy in range(scale):
                    y = y0 + gy * scale + sy
                    row_base = base + y * 4096
                    for sx in range(scale):
                        x = cx + gx * scale + sx
                        addr = row_base + (x % 1024) * 4
                        svc.exchange_write(S.build_0x9c(addr, lo))
                        svc.exchange_write(S.build_0x9c(addr + 2, hi))
                        n += 1
        cx += 6 * scale
    return n


if __name__ == '__main__':
    text = sys.argv[1] if len(sys.argv) > 1 else "HELLO MURDER"
    x = int(sys.argv[2], 0) if len(sys.argv) > 2 else 300
    y = int(sys.argv[3], 0) if len(sys.argv) > 3 else 30
    scale = int(sys.argv[4], 0) if len(sys.argv) > 4 else 4
    base = int(sys.argv[5], 0) if len(sys.argv) > 5 else 0x8DC00000
    svc = S.Service(settle=0.002)
    try:
        n = draw_text(svc, text, x, y, scale, base=base)
        print("drew %r: %d px at x=%d y=%d scale=%d" % (text, n, x, y, scale))
    finally:
        svc.close()


